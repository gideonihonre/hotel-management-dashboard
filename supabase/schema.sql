-- Database setup for the hotel management dashboard.
-- Paste this whole file into Supabase Dashboard -> SQL Editor -> New query, then click Run.

-- =========================================================
-- 1. Tables
-- Column names are camelCase to match the React code, so they must be quoted.
-- =========================================================

create table public.cabins (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text,
  "maxCapacity" smallint,
  "regularPrice" integer,
  discount integer default 0,
  description text,
  image text
);

create table public.guests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "fullName" text,
  email text,
  "nationalID" text,
  nationality text,
  "countryFlag" text
);

create table public.bookings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "startDate" timestamp,
  "endDate" timestamp,
  "numNights" smallint,
  "numGuests" smallint,
  "cabinPrice" real,
  "extrasPrice" real,
  "totalPrice" real,
  status text,
  "hasBreakfast" boolean default false,
  "isPaid" boolean default false,
  observations text,
  "cabinId" bigint references public.cabins (id) on delete cascade,
  "guestId" bigint references public.guests (id) on delete cascade
);

create table public.settings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "minBookingLength" smallint,
  "maxBookingLength" smallint,
  "maxGuestsPerBooking" smallint,
  "breakfastPrice" real
);

-- The app always reads/updates the settings row with id = 1.
insert into public.settings (id, "minBookingLength", "maxBookingLength", "maxGuestsPerBooking", "breakfastPrice")
values (1, 3, 30, 10, 15);

-- =========================================================
-- 2. Row Level Security: only logged-in staff can read/write
-- =========================================================

alter table public.cabins enable row level security;
alter table public.guests enable row level security;
alter table public.bookings enable row level security;
alter table public.settings enable row level security;

create policy "Authenticated full access" on public.cabins
  for all to authenticated using (true) with check (true);
create policy "Authenticated full access" on public.guests
  for all to authenticated using (true) with check (true);
create policy "Authenticated full access" on public.bookings
  for all to authenticated using (true) with check (true);
create policy "Authenticated full access" on public.settings
  for all to authenticated using (true) with check (true);

-- =========================================================
-- 3. Storage buckets (public so images can be shown via URL)
-- =========================================================

insert into storage.buckets (id, name, public)
values ('cabin-images', 'cabin-images', true),
       ('avatars', 'avatars', true);

create policy "Authenticated can upload images" on storage.objects
  for insert to authenticated
  with check (bucket_id in ('cabin-images', 'avatars'));

create policy "Authenticated can update images" on storage.objects
  for update to authenticated
  using (bucket_id in ('cabin-images', 'avatars'));

create policy "Authenticated can delete images" on storage.objects
  for delete to authenticated
  using (bucket_id in ('cabin-images', 'avatars'));
